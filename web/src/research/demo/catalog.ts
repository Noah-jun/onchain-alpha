const WIGGLE = [0, 0.15, -0.1, 0.2, -0.05, 0.1, -0.2, 0.05, 0.12, -0.08, 0.04, -0.03, 0.18, -0.12, 0.06, 0.02, -0.09, 0.11, -0.04, 0.07, -0.02, 0.05, -0.06, 0.03, 0]

export function demoHistory(price: number, change24h: number): HistoryPoint[] {
  const start = price / (1 + change24h / 100)
  const endMs = new Date(DEMO_UPDATED_AT).getTime()
  return WIGGLE.map((wiggle, index) => {
    const progress = index / (WIGGLE.length - 1)
    const base = start + (price - start) * progress
    const value = index === WIGGLE.length - 1 ? price : base + price * 0.0015 * wiggle
    const digits = price >= 100 ? 2 : 4
    return {
      t: new Date(endMs - (WIGGLE.length - 1 - index) * 60 * 60 * 1000).toISOString(),
      price: Number(value.toFixed(digits)),
    }
  })
}

function note(partial: Omit<ResearchNote, 'heatTags' | 'relatedAssets' | 'evidence' | 'risks' | 'counterpoints' | 'facts' | 'inferences' | 'unknowns'> & Partial<ResearchNote>): ResearchNote {
  return {
    heatTags: [],
    relatedAssets: [],
    evidence: [],
    risks: [],
    counterpoints: [],
    facts: [],
    inferences: [],
    unknowns: [],
    ...partial,
  }
}

function quote(
  symbol: string,
  name: string,
  assetClass: Quote['assetClass'],
  price: number,
  change24h: number,
  source: string
): Quote {
  return {
    symbol,
    name,
    assetClass,
    price,
    change24h,
    currency: 'USD',
    history: demoHistory(price, change24h),
    provenance: demoProvenance(source),
  }
}

